#include "msl_rt.h"

/* Shared by every ray tracing stage library and the dispatch kernel. Stages
 * are Metal visible functions taking a kk_rt_call frame in device memory; any-
 * hit and intersection shaders also get intersection function wrappers called
 * through the intersection function buffer, which is the Vulkan hit shader
 * binding table itself. See kk_rt_pipeline.c for the record layout. */
const char *msl_rt_preamble =
   "#include <metal_raytracing>\n"
   "#ifndef KK_RT_PREAMBLE\n"
   "#define KK_RT_PREAMBLE\n"
   "struct kk_rt_call {\n"
   "   ulong root;            /* root descriptor table (buf0) */\n"
   "   ulong sampler_table;   /* sampler heap (buffer 1) */\n"
   "   ulong vft;             /* address of the visible function table's resource ID */\n"
   "   ulong stack;           /* first free byte of this thread's ray tracing stack */\n"
   "   ulong hit_sbt;\n"
   "   ulong miss_sbt;\n"
   "   ulong callable_sbt;\n"
   "   ulong hit_sbt_size;\n"
   "   uint hit_stride;\n"
   "   uint miss_stride;\n"
   "   uint callable_stride;\n"
   "   uint ahit_status;      /* any-hit outcome: 0 accept, 1 ignore, 2 terminate */\n"
   "   uint3 launch_id;\n"
   "   uint ray_flags;\n"
   "   uint3 launch_size;\n"
   "   uint cull_mask;\n"
   "   ulong payload;         /* incoming payload or callable data */\n"
   "   ulong record;          /* this shader's SBT record */\n"
   "   float3 world_origin;\n"
   "   float tmin;\n"
   "   float3 world_direction;\n"
   "   float tmax;            /* hit distance in hit shaders */\n"
   "   float3 object_origin;\n"
   "   uint hit_kind;\n"
   "   float3 object_direction;\n"
   "   uint primitive_id;\n"
   "   uint instance_id;\n"
   "   uint custom_index;\n"
   "   uint geometry_index;\n"
   "   float box_t;           /* closest reported procedural hit */\n"
   "   float4x3 object_to_world;\n"
   "   float4x3 world_to_object;\n"
   "   uchar attribs[32];\n"
   "   uchar isec_attribs[32];\n"
   "};\n"
   "#define KK_RT_FRAME_SIZE 512u\n"
   "static_assert(sizeof(kk_rt_call) <= KK_RT_FRAME_SIZE, \"frame\");\n"
   "using kk_rt_fn = void(device kk_rt_call *);\n"
   "struct kk_rt_ray_data { device kk_rt_call *frame; };\n"
   "struct kk_rt_tri_result { bool accept [[accept_intersection]]; bool continue_search [[continue_search]]; };\n"
   "struct kk_rt_box_result { bool accept [[accept_intersection]]; bool continue_search [[continue_search]]; float distance [[distance]]; };\n"
   "\n"
   "static inline device kk_rt_call *\n"
   "kk_rt_new_frame(device kk_rt_call *call)\n"
   "{\n"
   "   device kk_rt_call *callee = (device kk_rt_call *)call->stack;\n"
   "   callee->root = call->root;\n"
   "   callee->sampler_table = call->sampler_table;\n"
   "   callee->vft = call->vft;\n"
   "   callee->stack = call->stack + KK_RT_FRAME_SIZE;\n"
   "   callee->hit_sbt = call->hit_sbt;\n"
   "   callee->miss_sbt = call->miss_sbt;\n"
   "   callee->callable_sbt = call->callable_sbt;\n"
   "   callee->hit_sbt_size = call->hit_sbt_size;\n"
   "   callee->hit_stride = call->hit_stride;\n"
   "   callee->miss_stride = call->miss_stride;\n"
   "   callee->callable_stride = call->callable_stride;\n"
   "   callee->launch_id = call->launch_id;\n"
   "   callee->launch_size = call->launch_size;\n"
   "   return callee;\n"
   "}\n"
   "\n"
   "static inline uint\n"
   "kk_rt_record_function(ulong record)\n"
   "{\n"
   "   return record ? *(const device uint *)(record + 8u) : 0u;\n"
   "}\n"
   "\n"
   "static void\n"
   "kk_rt_trace_ray(device kk_rt_call *call, ulong as_addr, uint flags, uint cull_mask,\n"
   "                uint sbt_offset, uint sbt_stride, uint miss_index, float3 origin,\n"
   "                float tmin, float3 direction, float tmax, ulong payload)\n"
   "{\n"
   "   device kk_rt_call *callee = kk_rt_new_frame(call);\n"
   "   callee->payload = payload;\n"
   "   callee->ray_flags = flags;\n"
   "   callee->cull_mask = cull_mask;\n"
   "   callee->world_origin = origin;\n"
   "   callee->world_direction = direction;\n"
   "   callee->tmin = tmin;\n"
   "   callee->tmax = tmax;\n"
   "   visible_function_table<kk_rt_fn> vft = *(constant visible_function_table<kk_rt_fn> *)call->vft;\n"
   "\n"
   "   raytracing::intersector<raytracing::triangle_data, raytracing::instancing,\n"
   "                           raytracing::world_space_data,\n"
   "                           raytracing::intersection_function_buffer> isect;\n"
   "   isect.set_base_id(sbt_offset);\n"
   "   isect.set_geometry_multiplier(sbt_stride);\n"
   "   isect.force_opacity((flags & 0x1u) ? raytracing::forced_opacity::opaque : (flags & 0x2u) ? raytracing::forced_opacity::non_opaque : raytracing::forced_opacity::none);\n"
   "   isect.set_opacity_cull_mode((flags & 0x40u) ? raytracing::opacity_cull_mode::opaque : (flags & 0x80u) ? raytracing::opacity_cull_mode::non_opaque : raytracing::opacity_cull_mode::none);\n"
   "   isect.set_triangle_cull_mode((flags & 0x10u) ? raytracing::triangle_cull_mode::back : (flags & 0x20u) ? raytracing::triangle_cull_mode::front : raytracing::triangle_cull_mode::none);\n"
   "   isect.set_geometry_cull_mode((flags & 0x100u) ? raytracing::geometry_cull_mode::triangle : (flags & 0x200u) ? raytracing::geometry_cull_mode::bounding_box : raytracing::geometry_cull_mode::none);\n"
   "   isect.accept_any_intersection((flags & 0x4u) != 0u);\n"
   "\n"
   "   raytracing::intersection_function_buffer_arguments ifb;\n"
   "   ifb.intersection_function_buffer = (const device void *)call->hit_sbt;\n"
   "   ifb.intersection_function_buffer_size = call->hit_sbt_size;\n"
   "   ifb.intersection_function_stride = call->hit_stride;\n"
   "\n"
   "   kk_rt_ray_data rd = {callee};\n"
   "   auto hit = isect.intersect(raytracing::ray(origin, direction, tmin, tmax),\n"
   "                              as_addr ? *(constant raytracing::instance_acceleration_structure *)as_addr\n"
   "                                      : raytracing::instance_acceleration_structure(),\n"
   "                              cull_mask, ifb, rd);\n"
   "\n"
   "   if (hit.type == raytracing::intersection_type::none) {\n"
   "      callee->record = call->miss_sbt ? call->miss_sbt + miss_index * call->miss_stride : 0ul;\n"
   "      uint fn = kk_rt_record_function(callee->record);\n"
   "      if (fn)\n"
   "         vft[fn](callee);\n"
   "      return;\n"
   "   }\n"
   "   if (flags & 0x8u) /* SkipClosestHitShader */\n"
   "      return;\n"
   "\n"
   "   callee->record = call->hit_sbt + (ulong)hit.function_id * call->hit_stride;\n"
   "   callee->tmax = hit.distance;\n"
   "   callee->primitive_id = hit.primitive_id;\n"
   "   callee->instance_id = hit.instance_id;\n"
   "   callee->custom_index = hit.user_instance_id;\n"
   "   callee->geometry_index = hit.geometry_id;\n"
   "   callee->object_to_world = hit.object_to_world_transform;\n"
   "   callee->world_to_object = hit.world_to_object_transform;\n"
   "   callee->object_origin = hit.world_to_object_transform * float4(origin, 1.0f);\n"
   "   callee->object_direction = hit.world_to_object_transform * float4(direction, 0.0f);\n"
   "   if (hit.type == raytracing::intersection_type::triangle) {\n"
   "      callee->hit_kind = hit.triangle_front_facing ? 0xFEu : 0xFFu;\n"
   "      *(device float2 *)callee->attribs = hit.triangle_barycentric_coord;\n"
   "   }\n"
   "   uint fn = kk_rt_record_function(callee->record);\n"
   "   if (fn)\n"
   "      vft[fn](callee);\n"
   "}\n"
   "\n"
   "static void\n"
   "kk_rt_execute_callable(device kk_rt_call *call, uint index, ulong data)\n"
   "{\n"
   "   device kk_rt_call *callee = kk_rt_new_frame(call);\n"
   "   callee->payload = data;\n"
   "   callee->record = call->callable_sbt + (ulong)index * call->callable_stride;\n"
   "   visible_function_table<kk_rt_fn> vft = *(constant visible_function_table<kk_rt_fn> *)call->vft;\n"
   "   uint fn = kk_rt_record_function(callee->record);\n"
   "   if (fn)\n"
   "      vft[fn](callee);\n"
   "}\n"
   "\n"
   "/* Procedural hits: keep the closest report within the ray's range. */\n"
   "static bool\n"
   "kk_rt_report_intersection(device kk_rt_call *call, float t, uint kind)\n"
   "{\n"
   "   if (t < call->tmin || t > call->box_t)\n"
   "      return false;\n"
   "   call->box_t = t;\n"
   "   call->hit_kind = kind;\n"
   "   for (uint i = 0; i < 32; i++)\n"
   "      call->attribs[i] = call->isec_attribs[i];\n"
   "   return true;\n"
   "}\n"
   "#endif\n";

const char *msl_rt_dispatch_source =
   "#ifndef KK_RT_DISPATCH\n"
   "#define KK_RT_DISPATCH\n"
   "struct kk_rt_dispatch_args {\n"
   "   ulong root;\n"
   "   ulong sampler_table;\n"
   "   ulong vft;\n"
   "   ulong hit_sbt;\n"
   "   ulong miss_sbt;\n"
   "   ulong callable_sbt;\n"
   "   ulong hit_sbt_size;\n"
   "   ulong raygen_record;\n"
   "   ulong stack_base;\n"
   "   uint hit_stride;\n"
   "   uint miss_stride;\n"
   "   uint callable_stride;\n"
   "   uint stack_size;       /* bytes per thread */\n"
   "   uint launch_size[3];\n"
   "   uint pad;\n"
   "   ulong indirect;        /* VkTraceRaysIndirectCommandKHR, or 0 */\n"
   "   ulong vft_id;          /* args.vft points here */\n"
   "};\n"
   "\n"
   "/* Runs the raygen shader for every launch ID. A bounded number of threads loop\n"
   " * over the launch, so the ray tracing stack scales with the threads, not the\n"
   " * launch size. */\n"
   "kernel void kk_rt_dispatch(constant kk_rt_dispatch_args &args [[buffer(0)]],\n"
   "                           uint tid [[thread_position_in_grid]],\n"
   "                           uint thread_count [[threads_per_grid]])\n"
   "{\n"
   "   device kk_rt_call *call =\n"
   "      (device kk_rt_call *)(args.stack_base + (ulong)tid * args.stack_size);\n"
   "   const uint3 size = args.indirect\n"
   "                         ? *(const device packed_uint3 *)args.indirect\n"
   "                         : uint3(args.launch_size[0], args.launch_size[1],\n"
   "                                 args.launch_size[2]);\n"
   "   const uint total = size.x * size.y * size.z;\n"
   "   visible_function_table<kk_rt_fn> vft =\n"
   "      *(constant visible_function_table<kk_rt_fn> *)args.vft;\n"
   "   const uint fn = kk_rt_record_function(args.raygen_record);\n"
   "\n"
   "   for (uint linear = tid; linear < total; linear += thread_count) {\n"
   "      call->root = args.root;\n"
   "      call->sampler_table = args.sampler_table;\n"
   "      call->vft = args.vft;\n"
   "      call->stack = (ulong)call + KK_RT_FRAME_SIZE;\n"
   "      call->hit_sbt = args.hit_sbt;\n"
   "      call->miss_sbt = args.miss_sbt;\n"
   "      call->callable_sbt = args.callable_sbt;\n"
   "      call->hit_sbt_size = args.hit_sbt_size;\n"
   "      call->hit_stride = args.hit_stride;\n"
   "      call->miss_stride = args.miss_stride;\n"
   "      call->callable_stride = args.callable_stride;\n"
   "      call->launch_size = size;\n"
   "      call->launch_id = uint3(linear % size.x, (linear / size.x) % size.y,\n"
   "                              linear / (size.x * size.y));\n"
   "      call->record = args.raygen_record;\n"
   "      call->payload = 0ul;\n"
   "      if (fn)\n"
   "         vft[fn](call);\n"
   "   }\n"
   "}\n"
   "\n"
   "/* Hit groups without an any-hit or intersection shader */\n"
   "[[intersection(triangle, raytracing::triangle_data, raytracing::instancing,\n"
   "               raytracing::world_space_data,\n"
   "               raytracing::intersection_function_buffer)]]\n"
   "kk_rt_tri_result kk_rt_default_triangle(ray_data kk_rt_ray_data &rd [[payload]])\n"
   "{\n"
   "   return {true, true};\n"
   "}\n"
   "\n"
   "[[intersection(bounding_box, raytracing::instancing,\n"
   "               raytracing::world_space_data,\n"
   "               raytracing::intersection_function_buffer)]]\n"
   "kk_rt_box_result kk_rt_default_box(ray_data kk_rt_ray_data &rd [[payload]])\n"
   "{\n"
   "   return {false, true, 0.0f};\n"
   "}\n"
   "#endif\n";
