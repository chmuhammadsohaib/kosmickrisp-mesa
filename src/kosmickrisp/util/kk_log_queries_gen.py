"""Generates field printers for the structs games query and pass at device
creation, for KK_LOG_QUERIES (see kk_log_queries.h)."""

import argparse
import xml.etree.ElementTree as et

# Structs whose pNext chains get logged, and the plain structs logged directly
CHAIN_ROOTS = ['VkPhysicalDeviceFeatures2', 'VkPhysicalDeviceProperties2',
               'VkDeviceCreateInfo']
DIRECT_ROOTS = ['VkPhysicalDeviceFeatures', 'VkPhysicalDeviceProperties']

SCALAR_FORMATS = {
    'VkBool32': ('%u', 'unsigned'),
    'uint8_t': ('%u', 'unsigned'),
    'uint16_t': ('%u', 'unsigned'),
    'uint32_t': ('%u', 'unsigned'),
    'int32_t': ('%d', 'int'),
    'uint64_t': ('%" PRIu64 "', 'uint64_t'),
    'int64_t': ('%" PRId64 "', 'int64_t'),
    'VkDeviceSize': ('%" PRIu64 "', 'uint64_t'),
    'VkDeviceAddress': ('0x%" PRIx64 "', 'uint64_t'),
    'size_t': ('%zu', 'size_t'),
    'float': ('%g', 'double'),
}


def api_ok(elem):
    api = elem.get('api')
    return api is None or 'vulkan' in api.split(',')


def load(xml_path):
    root = et.parse(xml_path).getroot()

    platforms = {p.get('name'): p.get('protect')
                 for p in root.find('platforms')}

    # Types available in the Vulkan headers, with the define guarding them
    available = {}
    for feature in root.findall('feature'):
        if 'vulkan' not in feature.get('api', '').split(','):
            continue
        for req in feature.findall('require'):
            for t in req.findall('type'):
                available.setdefault(t.get('name'), None)
    for ext in root.find('extensions'):
        if 'vulkan' not in ext.get('supported', '').split(','):
            continue
        guard = None
        if ext.get('platform'):
            guard = platforms[ext.get('platform')]
        elif ext.get('provisional') == 'true':
            guard = 'VK_ENABLE_BETA_EXTENSIONS'
        for req in ext.findall('require'):
            if not api_ok(req):
                continue
            for t in req.findall('type'):
                name = t.get('name')
                if name not in available or available[name] is not None:
                    available[name] = guard

    categories = {}
    structs = {}
    for t in root.find('types'):
        name = t.get('name') or (t.find('name').text if t.find('name') is not None else None)
        if not name or not api_ok(t):
            continue
        categories[name] = t.get('category')
        if t.get('category') == 'struct' and not t.get('alias'):
            structs[name] = t
    return available, categories, structs


def member_info(member):
    """(type, name, array dimension text or None, is pointer)"""
    mtype = member.find('type').text
    mname = member.find('name').text
    tail = member.find('name').tail or ''
    dim = None
    if tail.startswith('['):
        enum = member.find('enum')
        dim = enum.text if enum is not None else tail.strip('[]').split(']')[0]
    pointer = '*' in (member.find('type').tail or '')
    return mtype, mname, dim, pointer


def struct_stype(struct):
    for m in struct.findall('member'):
        if m.find('name').text == 'sType' and m.get('values'):
            return m.get('values')
    return None


def generate(xml_path):
    available, categories, structs = load(xml_path)

    wanted = set(DIRECT_ROOTS)
    for name, s in structs.items():
        extends = (s.get('structextends') or '').split(',')
        if name in available and any(r in extends for r in CHAIN_ROOTS):
            wanted.add(name)
    wanted.update(CHAIN_ROOTS)

    # Nested structs (by value) need printers too
    pending = list(wanted)
    while pending:
        name = pending.pop()
        for m in structs[name].findall('member'):
            if not api_ok(m):
                continue
            mtype, _, _, pointer = member_info(m)
            if not pointer and categories.get(mtype) == 'struct' and mtype not in wanted:
                wanted.add(mtype)
                pending.append(mtype)

    order = sorted(n for n in wanted if n in structs and n in available)
    out = []
    w = out.append

    w('/* Generated by kk_log_queries_gen.py, don\'t edit. */')
    w('#include "kk_log_queries.h"')
    w('')
    w('#include "vk_enum_to_str.h"')
    w('')
    w('#include <inttypes.h>')
    w('#include <stdio.h>')
    w('')

    def guarded(name, lines):
        guard = available.get(name)
        if guard:
            out.append('#ifdef %s' % guard)
        out.extend(lines)
        if guard:
            out.append('#endif')

    for name in order:
        guarded(name, ['static void print_%s(const char *prefix, const %s *s);' % (name, name)])
    w('')

    for name in order:
        lines = ['static void', 'print_%s(const char *prefix, const %s *s)' % (name, name), '{',
                 '   char field[512];', '   (void)field;']
        for m in structs[name].findall('member'):
            if not api_ok(m):
                continue
            mtype, mname, dim, pointer = member_info(m)
            if mname in ('sType', 'pNext'):
                continue
            if pointer or categories.get(mtype) in ('funcpointer', 'handle'):
                lines.append('   fprintf(stderr, "[kk] %%s.%s = %%p\\n", prefix, (const void *)s->%s);' % (mname, mname))
            elif dim and mtype == 'char':
                lines.append('   fprintf(stderr, "[kk] %%s.%s = \\"%%s\\"\\n", prefix, s->%s);' % (mname, mname))
            elif dim and mtype == 'uint8_t':
                lines += ['   fprintf(stderr, "[kk] %%s.%s =", prefix);' % mname,
                          '   for (unsigned i = 0; i < %s; i++)' % dim,
                          '      fprintf(stderr, " %%02x", s->%s[i]);' % mname,
                          '   fprintf(stderr, "\\n");']
            elif dim:
                if categories.get(mtype) == 'struct' and mtype in order:
                    lines += ['   for (unsigned i = 0; i < %s; i++) {' % dim,
                              '      snprintf(field, sizeof(field), "%%s.%s[%%u]", prefix, i);' % mname,
                              '      print_%s(field, &s->%s[i]);' % (mtype, mname),
                              '   }']
                else:
                    fmt, cast = SCALAR_FORMATS.get(mtype, ('%d', 'int'))
                    lines += ['   for (unsigned i = 0; i < %s; i++)' % dim,
                              '      fprintf(stderr, "[kk] %%s.%s[%%u] = %s\\n", prefix, i, (%s)s->%s[i]);'
                              % (mname, fmt, cast, mname)]
            elif categories.get(mtype) == 'struct':
                if mtype in order:
                    lines += ['   snprintf(field, sizeof(field), "%%s.%s", prefix);' % mname,
                              '   print_%s(field, &s->%s);' % (mtype, mname)]
            elif categories.get(mtype) == 'union':
                lines.append('   fprintf(stderr, "[kk] %%s.%s = (union)\\n", prefix);' % mname)
            elif categories.get(mtype) == 'bitmask':
                lines.append('   fprintf(stderr, "[kk] %%s.%s = 0x%%" PRIx64 "\\n", prefix, (uint64_t)s->%s);'
                             % (mname, mname))
            elif categories.get(mtype) == 'enum':
                if mtype in ('VkDriverId', 'VkPhysicalDeviceType', 'VkStructureType'):
                    lines.append('   fprintf(stderr, "[kk] %%s.%s = %%d (%%s)\\n", prefix, (int)s->%s, vk_%s_to_str(s->%s));'
                                 % (mname, mname, mtype[2:], mname))
                else:
                    lines.append('   fprintf(stderr, "[kk] %%s.%s = %%d\\n", prefix, (int)s->%s);' % (mname, mname))
            else:
                fmt, cast = SCALAR_FORMATS.get(mtype, ('%" PRIu64 "', 'uint64_t'))
                lines.append('   fprintf(stderr, "[kk] %%s.%s = %s\\n", prefix, (%s)s->%s);' % (mname, fmt, cast, mname))
        lines += ['}', '']
        guarded(name, lines)

    w('void')
    w('kk_log_struct(const char *prefix, const void *data)')
    w('{')
    w('   const VkBaseInStructure *base = data;')
    w('   const char *name = vk_StructureType_to_str(base->sType);')
    w('   char field[512];')
    w('   snprintf(field, sizeof(field), "%s.%s", prefix, name);')
    w('   switch (base->sType) {')
    for name in order:
        stype = struct_stype(structs[name])
        if not stype:
            continue
        guarded(name, ['   case %s:' % stype, '      print_%s(field, data);' % name, '      break;'])
    w('   default:')
    w('      fprintf(stderr, "[kk] %s (fields not known)\\n", field);')
    w('      break;')
    w('   }')
    w('}')
    w('')
    w('void')
    w('kk_log_features(const char *prefix, const VkPhysicalDeviceFeatures *features)')
    w('{')
    w('   print_VkPhysicalDeviceFeatures(prefix, features);')
    w('}')
    w('')
    w('void')
    w('kk_log_properties(const char *prefix, const VkPhysicalDeviceProperties *properties)')
    w('{')
    w('   print_VkPhysicalDeviceProperties(prefix, properties);')
    w('}')
    return '\n'.join(out) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--xml', required=True)
    parser.add_argument('--out-c', required=True)
    args = parser.parse_args()
    with open(args.out_c, 'w', encoding='utf-8') as f:
        f.write(generate(args.xml))


if __name__ == '__main__':
    main()
